import type { ModelRecord, DatasetRecord, ModelDomain } from './types.ts';

/**
 * Helper to build a standard demo dataset for a model
 */
function createDemoDataset(
  id: string,
  name: string,
  domain: ModelDomain,
  modelId: string,
  recordCount: number,
  features: string[],
  hasGroundTruth: boolean,
  labelColumn: string,
  fileFormat: 'csv' | 'json' | 'jsonl',
  description: string,
  isDemo = true,
  samplePreview?: Record<string, any>[]
): DatasetRecord {
  return {
    id,
    name: isDemo ? `${name} [DEMO DATA]` : name,
    domain,
    modelId,
    recordCount,
    featureCount: features.length,
    features,
    hasGroundTruth,
    labelColumn,
    isDemo,
    fileFormat,
    description,
    source: isDemo ? 'synthetic_demo' : 'verified_benchmark',
    uploadedAt: new Date(Date.now() - 86400000 * 3).toISOString(),
    samplePreview: samplePreview || [
      { [features[0] || 'f1']: 10.5, [features[1] || 'f2']: 'alpha', [labelColumn]: hasGroundTruth ? 'positive' : undefined },
      { [features[0] || 'f1']: 24.2, [features[1] || 'f2']: 'beta', [labelColumn]: hasGroundTruth ? 'negative' : undefined },
      { [features[0] || 'f1']: 8.7, [features[1] || 'f2']: 'alpha', [labelColumn]: hasGroundTruth ? 'positive' : undefined },
    ],
  };
}

